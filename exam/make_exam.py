def term(world, word):
    for t in OLD_W[world]["terms"]:
        if t.startswith(word + "（"):
            return t
    raise KeyError(word)


def old_world(name, address, words):
    w = OLD_W[name]
    return {"tone": w["tone"], "address": address, "terms": [term(name, x) for x in words],
            "banned": w["banned"], "offstage": w["offstage"]}


def norm_secret(x):
    if isinstance(x, str):
        return x
    v = [str(i) for i in x.values() if i]
    return v[0] + (f"（对外说：{v[1]}）" if len(v) > 1 else "")


def old_person(key, name, now=""):
    p = OLD_P[key]
    return {"name": name, **{k: p.get(k, "") for k in
            ["summary", "personality", "speech", "examples", "wants", "fears", "knows"]},
            "secrets": [norm_secret(s) for s in p.get("secrets", [])], "now": now}


def person(name, summary, personality, speech, examples, wants="", fears="", knows="", secrets=(), now=""):
    return {"name": name, "summary": summary, "personality": personality, "speech": speech,
            "examples": list(examples), "wants": wants, "fears": fears, "knows": knows,
            "secrets": list(secrets), "now": now}


def listener(name, summary, view, now="", others=()):
    return {"name": name, "summary": summary, "view": view, "now": now, "others": list(others)}


def h(name, text, emotion=""):
    return {"name": name, "emotion": emotion, "text": text}


def rules(use, lines, max_chars, emotions, speakers, actions=False):
    return {"use": use, "lines": list(lines), "max_chars": max_chars, "emotions": emotions,
            "actions": actions, "speakers": speakers}


